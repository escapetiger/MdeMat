function study = lowRankTransportStudy(options)
%LOWRANKTRANSPORTSTUDY Compare time/rank errors and total solver costs.
%   The dense exponential is an independent semidiscrete reference. Timed
%   callbacks include all evolution work, including QR/SVD and factor workspaces;
%   reference construction, assessment and artifact I/O are outside that scope.
%   Payload counts and a native process snapshot are reported separately.
%   The return value stays the numeric study structure. OutputFile stores a
%   separate RunRecord; UTC/Seed/CodeVersion are explicit provenance inputs.
arguments
    options.SpatialCells (1, 1) double {mustBeInteger, mustBeGreaterThanOrEqual(options.SpatialCells, 3)} = 24
    options.Velocities (1, 1) double {mustBeInteger, mustBeGreaterThanOrEqual(options.Velocities, 3)} = 8
    options.Tolerances (1, :) double {mustBePositive, mustBeFinite} = [1e-2,1e-5,1e-9]
    options.Repetitions (1, 1) double {mustBeInteger, mustBePositive} = 3
    options.OutputFile (1, 1) string = ""
    options.UTC {mustBeTextScalar} = ''
    options.Seed = []
    options.CodeVersion {mustBeTextScalar} = ''
end
nx = options.SpatialCells; nv = options.Velocities;
hx = 1/nx; x = ((1:nx)'-0.5)*hx;
v = linspace(-1,1,nv); w = 2/nv*ones(nv,1);
initial = mdemat.data.tensor.MatrixFactors( ...
    [ones(nx,1),sin(2*pi*x),cos(4*pi*x)],diag([1,0.1,0.03]), ...
    [ones(nv,1),v',v'.^2],LeftMetric=hx*speye(nx),RightMetric=diag(w));
F0 = initial.materialize();
tFinal = 0.025; dt = min(0.001,0.5*hx); scattering = 0.7;
i = (1:nx)';
back = (speye(nx)-sparse(i,mod(i-2,nx)+1,1,nx,nx))/hx;
forward = (sparse(i,mod(i,nx)+1,1,nx,nx)-speye(nx))/hx;
collision = w*ones(1,nv)/sum(w)-eye(nv);
generator = -kron(diag(max(v,0)),back)-kron(diag(min(v,0)),forward) ...
    +scattering*kron(collision',speye(nx));
exact = reshape(expm(full(tFinal*generator))*F0(:),nx,nv);
dense = denseEuler(F0);
timeError = norm(sqrt(hx)*(dense-exact).*sqrt(w'), 'fro');
denseCost = mdemat.tools.analyze.benchmark(@() denseEuler(F0), ...
    scope="dense solve including operator construction", repetitions=options.Repetitions);
cases = cell(1,numel(options.Tolerances));
for index = 1:numel(cases)
    tolerance = options.Tolerances(index);
    operation = @() mdemat.application.radiation.solveLowRankTransport( ...
        initial,v,w,[0,tFinal],dt,Scattering=scattering,RelativeTolerance=tolerance);
    [solution, report] = operation();
    values = solution.Field.materialize();
    cases{index} = struct('RelativeTolerance',tolerance,'FinalRank',solution.Field.Rank, ...
        'RankHistory',report.Evolution.Ranks, ...
        'TotalError',norm(sqrt(hx)*(values-exact).*sqrt(w'),'fro'), ...
        'CompressionEffect',norm(sqrt(hx)*(values-dense).*sqrt(w'),'fro'), ...
        'MassDefect',report.FinalMass-report.InitialMass, ...
        'MinimumValue',min(values,[],'all'),'FactorPayloadEntries',solution.Field.StoredEntries, ...
        'Cost',mdemat.tools.analyze.benchmark(operation, ...
            scope="factor solve including operators and compression",repetitions=options.Repetitions));
end
study = struct('Schema','mdemat.lowrank-study','Version',1,'Release',version('-release'), ...
    'Computer',computer,'SpatialCells',nx,'VelocityPoints',nv,'FinalTime',tFinal, ...
    'Step',dt,'DensePayloadEntries',numel(F0),'DenseEulerTimeError',timeError, ...
    'DenseEvolutionCost',denseCost,'Cases',{cases}, ...
    'MetricNonzeros',nx+nv,'TransportOperatorNonzeros',nnz(back)+nnz(forward), ...
    'NativeMemory',mdemat.tools.analyze.memorySnapshot(), ...
    'MemoryScope','Process snapshot includes study/reference arrays and prior session allocations/caches; not an isolated peak.', ...
    'ErrorScope','Fixed space/velocity quadrature; separates time error and rank-compression effect.');
if options.OutputFile ~= ""
    validation = struct('Status', 'UNVERIFIED', ...
        'Criterion', 'Physical weighted Frobenius error at fixed space/velocity discretization', ...
        'Measurements', struct('DenseEulerTimeError', timeError, ...
        'CaseTotalErrors', cellfun(@(item) item.TotalError, cases)), ...
        'Reference', 'Independent dense semidiscrete matrix exponential', ...
        'Bounds', struct(), ...
        'Reason', 'No study acceptance bounds supplied; this reference does not assess continuum spatial error.');
    execution = struct('Status', 'COMPLETED', 'Cases', numel(cases), ...
        'Scope', 'Dense/factor evolution costs exclude reference construction, assessment and I/O');
    inputs = struct('SpatialCells', nx, 'VelocityPoints', nv, ...
        'Tolerances', options.Tolerances, 'TimeStep', dt, 'FinalTime', tFinal, ...
        'Scattering', scattering, 'Repetitions', options.Repetitions, ...
        'Velocities', v, 'VelocityWeights', w, 'Domain', [0, 1], ...
        'Initial', struct('U', initial.U, 'S', initial.S, 'V', initial.V, ...
        'Axes', initial.Axes, 'LeftMetric', initial.LeftMetric, 'RightMetric', initial.RightMetric));
    timings = struct('DenseEvolution', denseCost, ...
        'FactorEvolution', {cellfun(@(item) item.Cost, cases, UniformOutput=false)});
    record = mdemat.tools.io.createRunRecord(study, execution, validation=validation, ...
        inputs=inputs, timings=timings, utc=options.UTC, seed=options.Seed, codeVersion=options.CodeVersion);
    mdemat.tools.io.writeRecord(options.OutputFile, record);
end

    function F = denseEuler(F)
        % Match the factor consumer's total-call scope: include construction
        % of the same structured spatial/collision operators in every trial.
        localBack = (speye(nx)-sparse(i,mod(i-2,nx)+1,1,nx,nx))/hx;
        localForward = (sparse(i,mod(i,nx)+1,1,nx,nx)-speye(nx))/hx;
        localCollision = w*ones(1,nv)/sum(w)-eye(nv);
        time = 0;
        while time<tFinal
            h = min(dt,tFinal-time);
            F = F+h*(-(localBack*F).*max(v,0)-(localForward*F).*min(v,0)+scattering*F*localCollision);
            time = time+h;
        end
    end
end
