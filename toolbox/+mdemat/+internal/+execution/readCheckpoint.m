function record = readCheckpoint(file)
%READCHECKPOINT Read an explicit completed-step checkpoint value record.
%   R = readCheckpoint(FILE) validates the execution envelope. State-only
%   consumers pass R.state to an explicitly selected State.fromRecord method.
%   Resuming additionally validates model identity, State and ODE history before
%   replacing runtime resources. This function never chooses saved constructors.
record = mdemat.tools.io.readRecord(file);
expected = {'format','schemaVersion','phase','scheme','state','integrator','configuration'};
if ~isstruct(record) || ~isscalar(record) || ...
        ~isequal(sort(fieldnames(record)),sort(expected(:))) || ...
        ~isequal(record.format,'mdemat.molCheckpoint') || ...
        ~isnumeric(record.schemaVersion) || ~isscalar(record.schemaVersion) || ...
        ~ismember(record.schemaVersion,[1,2]) || ...
        ~isequal(record.phase,'completed-step') || ~ischar(record.scheme) || ~isrow(record.scheme) || ...
        ~isstruct(record.state) || ~isscalar(record.state) || ...
        ~isstruct(record.integrator) || ~isscalar(record.integrator) || ...
        ~isstruct(record.configuration) || ~isscalar(record.configuration)
    error('mdemat:persistence:InvalidCheckpoint','Invalid completed-step checkpoint envelope.');
end
end
