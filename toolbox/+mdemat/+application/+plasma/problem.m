function record = problem(spatialSpace, velocitySpace, initial, finalTime, timeStep, options)
%PROBLEM Describe the retained one-dimensional DG/Hermite plasma model.
%   initial(X,nh) returns nh-by-NPoints Hermite coefficient samples.
%   method='ap' uses the equilibrium-scaled APDGHS representation
%   f=sqrt(rhoInf)*M_T*sum_k D_k He_k(v/sqrt(T))/sqrt(k!).
%   method='dghs' uses f=M_T*sum_k D_k He_k/sqrt(k!). Configuration specifies
%   ion density, collision time, epsilon, boundaries and equilibrium fields.
%   The velocity domain is the real line; nh is a spectral truncation, not a
%   finite velocity box. config.vBBox only sets plotting limits; state.VBBox
%   reports the real-line domain.
%   Problem fields are closed; config intentionally retains open v4 metadata.
%   Velocity modes must be the ordered, normalized He_k(v/sqrt(T))/sqrt(k!)
%   times a centered Maxwellian of the same positive scalar temperature.
%   An explicit config.T0 must agree with that representation.
arguments
    spatialSpace mdemat.common.fem.FiniteElementSpace
    velocitySpace mdemat.common.fem.SpectralSpace
    initial {mustBeA(initial, 'function_handle')}
    finalTime (1, 1) {mustBeNumeric, mustBeReal, mustBeFinite, mustBeNonnegative}
    timeStep (1, 1) {mustBeNumeric, mustBeReal, mustBeFinite, mustBePositive}
    options.method {mustBeTextScalar, mustBeMember(options.method, {'ap', 'dghs'})} = 'ap'
    options.config (1, 1) struct = struct()
end
assert(spatialSpace.NDims == 1 && velocitySpace.NDims == 1 && velocitySpace.NDofs >= 2, ...
    'MdeMat:Plasma:UnsupportedRepresentation', ...
    'The retained plasma kernels require one spatial dimension and at least two Hermite modes.');
assert(~strcmp(options.method, 'ap') || ...
    strcmp(spatialSpace.Element.Approximator.Type, 'nodal'), ...
    'MdeMat:Plasma:UnsupportedRepresentation', ...
    'The retained AP equilibrium-product formulation requires a nodal spatial basis.');
temperature = validateVelocity(velocitySpace);
if isfield(options.config, 'T0')
    supplied = options.config.T0;
    assert(validTemperature(supplied), 'MdeMat:Plasma:InvalidTemperature', ...
        'config.T0 must be a finite, real, positive numeric scalar.');
    assert(abs(double(supplied)-double(temperature)) <= ...
        8*eps(max(1, abs(double(temperature)))), 'MdeMat:Plasma:TemperatureMismatch', ...
        'config.T0 must match the Maxwellian and Hermite velocity scaling.');
end
record = struct('schemaVersion', 1, 'model', 'vlasov-poisson-fokker-planck', ...
    'spatialSpace', spatialSpace, 'velocitySpace', velocitySpace, 'initial', initial, ...
    'finalTime', finalTime, 'timeStep', timeStep, 'method', char(options.method), ...
    'config', options.config);
end

function temperature = validateVelocity(space)
basis = space.Element.Approximator.Basis;
assert(isa(basis, 'mdemat.data.function.Product') && ...
    isa(basis.Rhs, 'mdemat.data.function.Maxwellian'), ...
    'MdeMat:Plasma:UnsupportedRepresentation', ...
    'Velocity modes require a normalized Hermite factor times a Maxwellian.');
temperature = basis.Rhs.Temperature;
assert(validTemperature(temperature), 'MdeMat:Plasma:InvalidTemperature', ...
    'The velocity Maxwellian temperature must be finite, real, positive and scalar.');
assert(isnumeric(basis.Rhs.Center) && isreal(basis.Rhs.Center) && ...
    isscalar(basis.Rhs.Center) && basis.Rhs.Center == 0, ...
    'MdeMat:Plasma:UnsupportedRepresentation', ...
    'The retained modal transport operators require a centered velocity Maxwellian.');
polynomial = basis.Lhs;
if isa(polynomial, 'mdemat.common.approximation.SeparableFunction')
    assert(polynomial.NFactors == 1, 'MdeMat:Plasma:UnsupportedRepresentation', ...
        'The retained plasma model uses one ordered Hermite velocity factor.');
    if polynomial.IsSparse
        assert(isequal(polynomial.Pattern.indexer.Cache, (1:space.NDofs).'), ...
            'MdeMat:Plasma:UnsupportedRepresentation', ...
            'Hermite velocity modes must retain the order k=0,...,nh-1.');
    end
    polynomial = polynomial.getFactor(1);
end
scale = 1;
if isa(polynomial, 'mdemat.data.function.Composition')
    map = polynomial.Rhs;
    assert(isa(map, 'mdemat.data.function.Linear') && isnumeric(map.A) && ...
        isreal(map.A) && isscalar(map.A) && isfinite(map.A) && ...
        (isempty(map.b) || (isnumeric(map.b) && isreal(map.b) && ...
            isscalar(map.b) && map.b == 0)), ...
        'MdeMat:Plasma:UnsupportedRepresentation', ...
        'Hermite arguments require the unshifted map v/sqrt(T).');
    scale = map.A;
    polynomial = polynomial.Lhs;
end
assert(isa(polynomial, 'mdemat.common.spectral.HermiteBasis') && ...
    isscalar(polynomial.IsNormalized) && logical(polynomial.IsNormalized) && ...
    polynomial.NCodims == space.NDofs && polynomial.MaxDegree == space.NDofs-1 && ...
    abs(double(scale)-1/sqrt(double(temperature))) <= ...
        8*eps(max(1, 1/sqrt(double(temperature)))), ...
    'MdeMat:Plasma:UnsupportedRepresentation', ...
    'Require ordered normalized Hermite modes scaled by the Maxwellian temperature.');
end

function valid = validTemperature(value)
valid = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value > 0;
end
