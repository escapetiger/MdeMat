function record = problem(spatialSpace, velocitySpace, initial, finalTime, timeStep, options)
%PROBLEM Describe linear radiation transport with explicit numerical spaces.
%   initial(X,V,t) returns a row for paired physical positions/velocities.
%   A finite scalar gives an isotropic constant distribution. config retains
%   the original MmDgScheme scales, decomposition, collisions and limiters.
%   Problem fields are closed; config intentionally retains open v4 metadata.
%   With timeScale=1, scatteringScale=-1, absorptionScale=1 the model is
%       epsilon*f_t+v.grad(f)=sigma/epsilon*(<f>-f)-epsilon*alpha*f+epsilon*s.
%   Other supported scale choices use MmDgScheme.Pattern.scaling explicitly.
arguments
    spatialSpace mdemat.common.fem.FiniteElementSpace
    velocitySpace mdemat.common.fem.SumSpace
    initial
    finalTime (1, 1) {mustBeNumeric, mustBeReal, mustBeFinite, mustBeNonnegative}
    timeStep (1, 1) {mustBeNumeric, mustBeReal, mustBeFinite, mustBePositive}
    options.config (1, 1) struct = struct()
end
assert(isa(initial, 'function_handle') || ...
    (isnumeric(initial) && isscalar(initial) && isfinite(initial)), ...
    'MdeMat:Radiation:InvalidInitialCondition', ...
    'Provide a paired kinetic function or a finite scalar.');
assert(velocitySpace.NDofs > 0, 'MdeMat:Radiation:EmptyVelocitySpace', ...
    'At least one macro or microscopic velocity space is required.');
for side = {velocitySpace.Lhs, velocitySpace.Rhs}
    if ~isempty(side{1})
        assert(isa(side{1}.Element, 'mdemat.common.fem.L2SphereElement'), ...
            'MdeMat:Radiation:UnsupportedRepresentation', ...
            'The retained transport kernel requires angular L2SphereElement spaces.');
        assert(side{1}.Element.Geometry.NDims >= spatialSpace.NDims, ...
            'MdeMat:Radiation:VelocityDimension', ...
            'The physical velocity dimension must cover every spatial direction.');
    end
end
if ~isempty(velocitySpace.Lhs)
    assert(isa(velocitySpace.Lhs.Element.Approximator.Basis, ...
        'mdemat.data.function.Product'), 'MdeMat:Radiation:UnsupportedRepresentation', ...
        'The macro space requires the retained product-form angular basis.');
end
if ~isempty(velocitySpace.Lhs) && ~isempty(velocitySpace.Rhs)
    left = velocitySpace.Lhs.Element;
    right = velocitySpace.Rhs.Element;
    assert(strcmp(class(left.Geometry), class(right.Geometry)) && ...
        isequal(left.Geometry.BBox, right.Geometry.BBox) && ...
        left.Approximator.Basis.NDims == right.Approximator.Basis.NDims, ...
        'MdeMat:Radiation:IncompatibleVelocitySpaces', ...
        'Macro and microscopic modes must share the physical domain and coordinate chart.');
end
record = struct('schemaVersion', 1, 'model', 'linear-radiation', ...
    'spatialSpace', spatialSpace, 'velocitySpace', velocitySpace, 'initial', initial, ...
    'finalTime', finalTime, 'timeStep', timeStep, 'config', options.config);
end
