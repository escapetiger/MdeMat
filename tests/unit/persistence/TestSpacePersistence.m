classdef TestSpacePersistence < matlab.unittest.TestCase
    methods (Test)
        function basesAndFunctionCompositionsRetainValuesAndAxes(testCase)
            bases = {mdemat.common.approximation.CompiledFunction(1, 3, 'normal_legendre'), ...
                mdemat.common.spectral.CompiledOrthogonalBasis(3, 'normal_hermite'), ...
                mdemat.common.interpolation.CompiledInterpolationBasis(3, 'unit_gauss_legendre_lagrange'), ...
                mdemat.common.spectral.LegendreBasis(3, isNormalized=true), ...
                mdemat.common.spectral.HermiteBasis(3, isNormalized=false), ...
                mdemat.common.spectral.ChebyshevBasis(3, isNormalized=true), ...
                mdemat.common.spectral.FourierBasis(2, isNormalized=true, lower=-0.7, upper=2.1), ...
                mdemat.common.spectral.SphericalHarmonicBasis(2, isNormalized=true), ...
                mdemat.common.interpolation.CardinalKernelBasis([-0.3, 0.1, 0.4]), ...
                mdemat.common.interpolation.RbfKernelBasis([-0.3, 0.1, 0.4], epsilon=[1; 2; 3]), ...
                mdemat.data.function.Constant(2, [1+2i; -3i]), ...
                mdemat.data.function.Linear([1, 1i; 0, 2], b=[1; -2i]), ...
                mdemat.data.function.Maxwellian(2, temperature=0.7, center=[0.3; -0.2])};
            bases{end+1} = mdemat.data.function.Composition( ...
                mdemat.common.spectral.LegendreBasis(3), mdemat.data.function.Linear(2, b=0.1));
            bases{end+1} = mdemat.data.function.Product( ...
                mdemat.common.spectral.LegendreBasis(2), mdemat.data.function.Constant(1, 2i));
            for pattern = {'', 'P', 'Q'}
                bases{end+1} = mdemat.common.approximation.SeparableFunction( ...
                    factors={mdemat.common.spectral.LegendreBasis(2), ...
                    mdemat.common.spectral.HermiteBasis(2)}, pattern=pattern{1}); %#ok<AGROW>
            end
            for index = 1:numel(bases)
                original = bases{index};
                rebuilt = roundtrip(original);
                points = repmat([-0.23, 0.05, 0.31], original.NDims, 1);
                if original.NDims == 2, points(2, :) = [0.3, 0.8, 1.3]; end
                testCase.verifyClass(rebuilt, class(original));
                testCase.verifyEqual(rebuilt.NDims, original.NDims);
                testCase.verifyEqual(rebuilt.NCodims, original.NCodims);
                testCase.verifyEqual(rebuilt.eval(points), original.eval(points), 'AbsTol', 2e-13);
            end
            normalized = roundtrip(mdemat.common.spectral.LegendreBasis(1, isNormalized=true));
            testCase.verifyEqual(normalized.eval([0, 0.25]), ...
                [1/sqrt(2), 1/sqrt(2); 0, sqrt(3/2)/4], 'AbsTol', 8*eps);
        end

        function allConcreteGeometryAndMeshKindsRetainTopology(testCase)
            vertices = [0, 0; 1, 0; 1, 1; 0, 1];
            mesh = mdemat.data.mesh.Triangulation(vertices, [1, 2, 3; 1, 3, 4]);
            mesh.setPeriodic([0, 1, 0, 1]);
            % Four square boundary edges form two opposite periodic pairs.
            testCase.verifyEqual(nnz(mesh.FaceToFaceTable), 4);
            objects = {mdemat.data.geometry.Orthotope([-1, 2, -3, 4]), ...
                mdemat.data.geometry.Simplex([0, 1, 0; 0, 0, 1]), ...
                mdemat.data.geometry.Polytope([0, 1, 0; 0, 0, 1], {[1, 2], [2, 3], [3, 1]}), ...
                mdemat.data.geometry.Sphere([1, -2, 3], 0.7), ...
                mdemat.data.geometry.Ball([1, -2], 0.7), ...
                mdemat.data.mesh.Grid({[0, 0.2, 1], [-2, 0, 3]}), ...
                mdemat.data.mesh.UniformGrid([0, 1, -2, 3], [2, 3]), mesh, ...
                mdemat.data.mesh.Graph([0; 1; 2], [1, 2; 2, 3]), ...
                mdemat.data.mesh.SeparableGraph({[0; 1], [0; 2]}, {[1, 2], [1, 2]})};
            for index = 1:numel(objects)
                original = objects{index}; rebuilt = roundtrip(original);
                testCase.verifyClass(rebuilt, class(original));
                testCase.verifyEqual(mdemat.common.fem.describeSpace(rebuilt), ...
                    mdemat.common.fem.describeSpace(original));
            end
            rebuilt = roundtrip(mesh);
            testCase.verifyEqual(rebuilt.FaceToFaceTable, mesh.FaceToFaceTable);
            testCase.verifyEqual(rebuilt.collocate([0.2; 0.3]), mesh.collocate([0.2; 0.3]));
        end

        function rulesAndNumericQuadratureRetainCoordinatesAndWeights(testCase)
            rules = {mdemat.common.quadrature.GaussLegendreRule(2), ...
                mdemat.common.quadrature.GaussLobattoRule(2), ...
                mdemat.common.quadrature.ClosedNewtonCotesRule(2), ...
                mdemat.common.quadrature.PeriodicTrapezoidalRule(2), ...
                mdemat.common.quadrature.GaussHermiteRule(2), ...
                mdemat.common.quadrature.LebedevRule(coord='stdsph'), ...
                mdemat.common.quadrature.GaussTrapezoidalRule(3, coord='cossph'), ...
                mdemat.common.quadrature.MonteCarloOrthotopeRule(2, seed=17), ...
                mdemat.common.quadrature.MonteCarloSphereRule(3, seed=19, coord='car')};
            for index = 1:numel(rules)
                testCase.verifyEqual(mdemat.common.fem.describeSpace(roundtrip(rules{index})), ...
                    mdemat.common.fem.describeSpace(rules{index}));
            end
            integrator = mdemat.common.quadrature.Integrator(rules{1});
            integrator.setPoints(mdemat.data.geometry.Orthotope([-1, 2, -2, 3]), [3, 4]);
            integrator.addWeightFunction(@(x) 1 + x(1, :).^2);
            rebuilt = roundtrip(integrator);
            testCase.verifyEqual(rebuilt.Nodes, integrator.Nodes);
            testCase.verifyEqual(rebuilt.Weights, integrator.Weights);
            testCase.verifyEqual(sum(rebuilt.Weights), 30, 'AbsTol', 2e-13);
            levels = mdemat.common.quadrature.MultiLevelIntegrator(rules{1}, nLevels=3);
            testCase.verifyEqual(roundtrip(levels).NLevels, 3);
        end

        function everyElementKindAndSpaceCompositeRetainsEvaluation(testCase)
            element = mdemat.common.fem.BH1OrthotopeElement.modal(1, 3);
            g = element.Geometry; a = element.Approximator; v = element.Volume; f = element.Flux;
            elements = {mdemat.common.fem.Element(g, a), ...
                mdemat.common.fem.L2Element(g, a, v), mdemat.common.fem.H1Element(g, a, v), ...
                mdemat.common.fem.BH1Element(g, a, v, f), ...
                mdemat.common.fem.L2OrthotopeElement.hermite(1, 4, T=0.7), ...
                mdemat.common.fem.L2SphereElement.modal(3, 2, np=[4, 8]), ...
                element, mdemat.common.fem.BH1SLOrthotopeElement(g, a, v, f), ...
                mdemat.common.fem.BH1OrthotopeElement.nodal(1, 3), ...
                mdemat.common.fem.BH1OrthotopeElement.modal(2, 3, pattern='P')};
            for index = 1:numel(elements)
                original = elements{index}; rebuilt = roundtrip(original);
                points = repmat([-0.2, 0.1, 0.3], original.NDims, 1);
                coefficients = (1:original.NDofs).' + 1i/7;
                testCase.verifyClass(rebuilt, class(original));
                testCase.verifyEqual(rebuilt.eval(points, coefficients), ...
                    original.eval(points, coefficients), 'AbsTol', 2e-13);
                if isa(original, 'mdemat.common.fem.L2Element')
                    testCase.verifyEqual(rebuilt.Volume.Nodes, original.Volume.Nodes);
                    testCase.verifyEqual(rebuilt.Volume.Weights, original.Volume.Weights);
                    testCase.verifyEqual(rebuilt.Volume.Values, original.Volume.Values, 'AbsTol', 2e-13);
                end
                if isa(original, 'mdemat.common.fem.BH1Element')
                    testCase.verifyEqual(rebuilt.Flux(1).Weights, original.Flux(1).Weights);
                    testCase.verifyEqual(rebuilt.Flux(1).Values, original.Flux(1).Values);
                end
            end
            grid = mdemat.data.mesh.UniformGrid([0, 1], 3);
            spectral = mdemat.common.fem.SpectralSpace(element);
            spaces = {mdemat.common.fem.MeshSpace(grid), ...
                mdemat.common.fem.FiniteElementSpace(grid, element), spectral, ...
                mdemat.common.fem.AffineSpace(element), ...
                mdemat.common.fem.ScaledAffineSpace(element, [1; 2; 3; 0.5]), ...
                mdemat.common.fem.SumSpace(spectral, spectral, ...
                    lhsWeight=[1; 2; 3], rhsWeight=[-1; 1; 2]), ...
                mdemat.common.fem.SumSpace([], spectral)};
            for index = 1:numel(spaces)
                rebuilt = roundtrip(spaces{index});
                testCase.verifyEqual(mdemat.common.fem.describeSpace(rebuilt), ...
                    mdemat.common.fem.describeSpace(spaces{index}));
            end
            nodal = mdemat.common.approximation.NodalApproximator( ...
                mdemat.common.interpolation.CardinalKernelBasis([-0.2, 0.2]));
            linear = mdemat.common.approximation.LinearApproximator(nodal.Basis);
            testCase.verifyClass(roundtrip(nodal), class(nodal));
            testCase.verifyClass(roundtrip(linear), class(linear));
        end

        function unknownVersionsTagsAndFieldsAreRejected(testCase)
            record = mdemat.common.fem.describeSpace(mdemat.data.geometry.Sphere([0, 0, 0], 1));
            record.type = 'arbitrary.constructor';
            testCase.verifyError(@() mdemat.common.fem.restoreSpace(record), ...
                'mdemat:persistence:UnsupportedTag');
            record.type = 'geometry.sphere'; record.schemaVersion = 2;
            testCase.verifyError(@() mdemat.common.fem.restoreSpace(record), ...
                'mdemat:persistence:InvalidDescriptor');
            record.schemaVersion = 1; record.data.extra = 1;
            testCase.verifyError(@() mdemat.common.fem.restoreSpace(record), ...
                'mdemat:persistence:InvalidDescriptor');
            basis = mdemat.common.spectral.CompiledOrthogonalBasis(3, 'normal_legendre');
            record = mdemat.common.fem.describeSpace(basis);
            record.data.definition.functionText{1} = '@(x)999+0*x';
            testCase.verifyError(@() mdemat.common.fem.restoreSpace(record), ...
                'mdemat:persistence:ResourceChanged');
            record = mdemat.common.fem.describeSpace(basis);
            record.data.definition.functionText{1} = @sin;
            testCase.verifyError(@() mdemat.common.fem.restoreSpace(record), ...
                'mdemat:persistence:InvalidDescriptor');
        end
    end
end

function object = roundtrip(object)
object = mdemat.common.fem.restoreSpace(mdemat.common.fem.describeSpace(object));
end
